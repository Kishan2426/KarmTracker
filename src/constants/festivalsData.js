export function getUpcomingFestivals(allFestivals = DEFAULT_FESTIVALS, referenceDate = new Date()) {
  const refTime = new Date(referenceDate.getFullYear(), referenceDate.getMonth(), referenceDate.getDate()).getTime();

  return [...allFestivals]
    .map(fest => {
      const [year, month, day] = fest.date.split('-').map(Number);
      const festDate = new Date(year, month - 1, day);
      const diffMs = festDate.getTime() - refTime;
      const daysUntil = Math.ceil(diffMs / (1000 * 60 * 60 * 24));

      return {
        ...fest,
        daysUntil,
        isPast: daysUntil < 0,
        isToday: daysUntil === 0,
      };
    })
    .sort((a, b) => {
      if (a.daysUntil >= 0 && b.daysUntil >= 0) return a.daysUntil - b.daysUntil;
      if (a.daysUntil >= 0 && b.daysUntil < 0) return -1;
      if (a.daysUntil < 0 && b.daysUntil >= 0) return 1;
      return b.daysUntil - a.daysUntil;
    });
}
